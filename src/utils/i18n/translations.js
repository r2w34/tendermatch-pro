// Language context and hooks
export const useTranslation = (language = 'en') => {
  const t = (key) => {
    const keys = key.split('.');
    let value = translations[language];
    
    for (const k of keys) {
      value = value?.[k];
    }
    
    return value || key;
  };

  return { t };
};

// Language detection based on browser/user preference
export const detectLanguage = () => {
  const savedLanguage = localStorage.getItem('language');
  if (savedLanguage) return savedLanguage;
  
  const browserLanguage = navigator.language || navigator.languages[0];
  if (browserLanguage.startsWith('hi')) return 'hi';
  
  return 'en';
};

// Set language preference
export const setLanguage = (language) => {
  localStorage.setItem('language', language);
  document.documentElement.lang = language;
};

// Format numbers in Indian style
export const formatIndianNumber = (num, language = 'en') => {
  if (language === 'hi') {
    return num.toLocaleString('hi-IN');
  }
  return num.toLocaleString('en-IN');
};

// Format currency with language support
export const formatCurrencyWithLanguage = (amount, language = 'en') => {
  const { t } = useTranslation(language);
  
  if (amount >= 10000000) {
    return `₹${(amount / 10000000).toFixed(2)} ${t('crore')}`;
  } else if (amount >= 100000) {
    return `₹${(amount / 100000).toFixed(2)} ${t('lakh')}`;
  } else if (amount >= 1000) {
    return `₹${(amount / 1000).toFixed(0)} ${t('thousand')}`;
  }
  return `₹${formatIndianNumber(amount, language)}`;
};